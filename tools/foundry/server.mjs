const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml; charset=utf-8',
  '.woff2': 'font/woff2',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.md': 'text/markdown; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
};

const json = (res, status, data) => {
  const body = JSON.stringify(data, null, 2);
  res.writeHead(status, {
    'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'no-store',
    'Content-Length': Buffer.byteLength(body),
  });
  res.end(body);
};

const text = (res, status, body, type = 'text/plain; charset=utf-8') => {
  res.writeHead(status, {
    'Content-Type': type,
    'Cache-Control': 'no-store',
    'Content-Length': Buffer.byteLength(body),
  });
  res.end(body);
};

function safeFile(root, rel) {
  let decoded;
  try {
    decoded = decodeURIComponent(rel);
  } catch {
    return null;
  }
  const cleaned = decoded.replace(/\\/g, '/').replace(/^\/+/, '');
  const abs = path.resolve(root, cleaned);
  if (abs !== root && !abs.startsWith(root + path.sep)) return null;
  return abs;
}

async function sendFile(res, file, { cache = 'no-store' } = {}) {
  let stat;
  try {
    stat = await fsp.stat(file);
  } catch {
    return false;
  }
  if (!stat.isFile()) return false;
  const ext = path.extname(file).toLowerCase();
  res.writeHead(200, {
    'Content-Type': MIME[ext] || 'application/octet-stream',
    'Cache-Control': cache,
    'Content-Length': stat.size,
  });
  fs.createReadStream(file).pipe(res);
  return true;
}

// ── Live registry ───────────────────────────────────────────────────────────

async function registrySource() {
  const lib = await buildLibrary();
  const usable = lib.filter((r) => r.asset && !r.errors.length);
  const lines = [
    `// Generated by Foundry at ${new Date().toISOString()} — do not edit.`,
    '// Each module is cache-busted by mtime so only changed assets re-evaluate.',
  ];
  usable.forEach((r, i) => {
    lines.push(`import a${i} from ${JSON.stringify('/assets/' + r.file + '?v=' + Math.round(r.mtime))};`);
  });
  lines.push('');
  lines.push(`export default [${usable.map((_, i) => `a${i}`).join(', ')}];`);
  lines.push('');
  return lines.join('\n');
}

// ── SSE ─────────────────────────────────────────────────────────────────────

const clients = new Set();

function broadcast(payload) {
  const frame = `data: ${JSON.stringify(payload)}\n\n`;
  for (const res of clients) {
    try {
      res.write(frame);
    } catch {
      clients.delete(res);
    }
  }
}

function sse(req, res) {
  res.writeHead(200, {
    'Content-Type': 'text/event-stream; charset=utf-8',
    'Cache-Control': 'no-cache, no-transform',
    Connection: 'keep-alive',
    'X-Accel-Buffering': 'no',
  });
  res.write('retry: 1500\n\n');
  res.write(`data: ${JSON.stringify({ type: 'hello', at: Date.now() })}\n\n`);
  clients.add(res);
  req.on('close', () => clients.delete(res));
}

setInterval(() => {
  for (const res of clients) {
    try {
      res.write(': ping\n\n');
    } catch {
      clients.delete(res);
    }
  }
}, 20_000).unref();

let watchTimer = null;
let watcher = null;
try {
  watcher = fs.watch(ASSET_ROOT, { recursive: true }, () => {
    clearTimeout(watchTimer);
    watchTimer = setTimeout(() => {
      broadcast({ type: 'change', at: Date.now() });
    }, 180);
  });
} catch (err) {
  console.error('[foundry] asset watcher failed:', err.message);
}

// ── Routing ─────────────────────────────────────────────────────────────────

async function handler(req, res) {
  const url = new URL(req.url || '/', 'http://localhost');
  const pathname = url.pathname;

  try {
    if (pathname === '/api/events') return sse(req, res);

    if (pathname === '/api/assets') {
      const lib = await buildLibrary();
      return json(res, 200, {
        assets: lib.map(toPublic),
        count: lib.length,
        generatedAt: Date.now(),
        watch: Boolean(watcher),
      });
    }

    if (pathname === '/api/health') {
      return json(res, 200, { ok: true, at: Date.now() });
    }

    if (pathname === '/generated/registry.js') {
      const source = await registrySource();
      return text(res, 200, source, 'text/javascript; charset=utf-8');
    }

    if (pathname.startsWith('/api/asset/')) {
      const rest = pathname.slice('/api/asset/'.length).split('/');
      const key = decodeURIComponent(rest[0] || '');
      const action = rest[1] || '';
      const lib = await buildLibrary();
      const record = findRecord(lib, key);
      if (!record) return json(res, 404, { error: `No asset "${key}"` });

      if (action === 'source') {
        const source = await fsp.readFile(record.abs, 'utf8').catch(() => null);
        if (source == null) return json(res, 404, { error: 'Source unavailable' });
        res.writeHead(200, {
          'Content-Type': 'text/plain; charset=utf-8',
          'Cache-Control': 'no-store',
          'Content-Disposition': 'inline; filename="' + record.key + '.js"',
        });
        return res.end(source);
      }

      if (action === 'canvas' || action === 'painter') {
        if (!record.asset) return json(res, 400, { error: record.errors.join('\n') || 'No preview' });
        const angle = Number(url.searchParams.get('angle') ?? record.hero ?? 0) || 0;
        const code = assetToCanvasCode(record.asset, {
          angle,
          unit: 100,
        });
        res.writeHead(200, {
          'Content-Type': 'text/javascript; charset=utf-8',
          'Cache-Control': 'no-store',
          ...(url.searchParams.get('download')
            ? { 'Content-Disposition': `attachment; filename="${record.key}-canvas.js"` }
            : {}),
        });
        return res.end(code);
      }

      return json(res, 404, { error: 'Unknown asset action' });
    }

    if (pathname === '/favicon.svg') {
      return text(
        res,
        200,
        `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="8" fill="#3A3026"/><ellipse cx="16" cy="16" rx="9" ry="5" fill="none" stroke="#F7F4EC" stroke-width="1.8" transform="rotate(-24 16 16)"/><circle cx="23.2" cy="11.2" r="2.1" fill="#B08D3F"/></svg>`,
        'image/svg+xml; charset=utf-8',
      );
    }

    if (pathname === '/' || pathname === '/index.html') {
      return (await sendFile(res, path.join(WEB_ROOT, 'index.html'))) || text(res, 404, 'Missing UI');
    }

    const staticMap = [
      ['/css/', path.join(WEB_ROOT, 'css')],
      ['/js/', path.join(WEB_ROOT, 'js')],
      ['/fonts/', path.join(WEB_ROOT, 'fonts')],
      ['/assets/', ASSET_ROOT],
      ['/docs/', path.join(ROOT, 'docs')],
    ];

    for (const [prefix, root] of staticMap) {
      if (pathname.startsWith(prefix)) {
        const rel = pathname.slice(prefix.length);
        const file = safeFile(root, rel);
        if (!file) return text(res, 403, 'Forbidden');
        const cache = prefix === '/fonts/' ? 'public, max-age=3600' : 'no-store';
        if (await sendFile(res, file, { cache })) return;
        return text(res, 404, 'Not found');
      }
    }

    return text(res, 404, 'Not found');
  } catch (err) {
    console.error('[foundry]', err);
    if (!res.headersSent) return json(res, 500, { error: err.message });
    res.end();
  }
}

// ── Listen with port fallback ───────────────────────────────────────────────

const server = http.createServer(handler);
server.keepAliveTimeout = 30_000;

async function listen(startPort) {
  for (let port = startPort; port < startPort + 12; port++) {
    try {
      await new Promise((resolve, reject) => {
        const onError = (err) => {
          server.off('listening', onListening);
          reject(err);
        };
        const onListening = () => {
          server.off('error', onError);
          resolve();
        };
        server.once('error', onError);
        server.once('listening', onListening);
        server.listen(port, host);
      });
      return port;
    } catch (err) {
      if (err.code !== 'EADDRINUSE') throw err;
    }
  }
  throw new Error('No free port in range');
}

